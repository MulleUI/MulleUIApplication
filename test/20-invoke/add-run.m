#define _GNU_SOURCE

#import <MulleUIApplication/MulleUIApplication.h>

#include <time.h>


@interface Foo : NSObject
@end


@implementation Foo : NSObject

#ifdef LEAK_HUNT
- (id) retain
{
   mulle_printf( "%s: RC=%ld -+-> %ld\n", __FUNCTION__, [self retainCount], [self retainCount] + 1);
   return( [super retain]);
}

- (void) release
{
   mulle_printf( "%s: RC=%ld ---> %ld \n", __FUNCTION__, [self retainCount], [self retainCount] - 1);
   return( [super release]);
}

- (id) autorelease
{
   mulle_printf( "%s: RC=%ld (--> %ld)\n", __FUNCTION__, [self retainCount], [self retainCount] - 1);
   return( [super autorelease]);
}
#endif

- (id) callMe:(id) me
{
   mulle_printf( "called\n");
   return( self);
}

@end


int   main( int argc, char *argv[])
{
   UIApplication       *app;
   NSUInteger          i;
   NSMethodSignature   *signature;
   NSInvocation        *invocation;
   Foo                 *foo;
   id                  rval;

   app = [UIApplication sharedInstance];

   //
   // MEMO: UIApplication can store 128 invocations for the main thread
   //
   @autoreleasepool
   {
      foo = [Foo instance];

      signature  = [foo methodSignatureForSelector:@selector( callMe:)];
      invocation = [NSInvocation invocationWithMethodSignature:signature];
      [invocation setTarget:foo];
      [invocation setSelector:@selector( callMe:)];

      // not yet invoked (but added to runLoop)
      [app invokeOnMainThread:invocation];
      [app runInvocations];
      [invocation getReturnValue:&rval];
      [app setReturnStatus:rval != foo];
   }

   return( [app terminate]);
}



