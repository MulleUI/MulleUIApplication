#import "import.h"


@interface MyApplication : UIApplication <MulleObjCSingleton>
@end

@implementation MyApplication

// need this otherwise [UIApplication sharedInstance] code will
// get the wrong Application object
+ (instancetype) sharedInstance
{
   if( ! UIApp)
      UIApp = [super sharedInstance];

   assert( [UIApp isKindOfClass:[MyApplication class]]);
   return( (MyApplication *) UIApp);
}

@end 



int   main( int argc, char *argv[])
{
   UIWindow         *window;
   UIApplication    *app;

   app = [MyApplication sharedInstance];

   @autoreleasepool
   {
      window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 400.0, 400.0)];
      [window setBackgroundColor:CGColorMakeWithRGBA( 1.0, 0.75, 0.0, 1.0)];
      [app addWindow:window];
   }
   return( [app run]);
}



