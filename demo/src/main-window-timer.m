#import "import.h"


@implementation UIWindow ( RandomColor)

- (void) setWhiteBackgroundColor:(id) sender 
{
   [self setBackgroundColor:CGColorMakeRGBA( 1.0, 1.0, 1.0, 1.0)];
   [self setNeedsDisplay]; 
}

- (void) randomizeBackgroundColor:(id) sender 
{
   [self setBackgroundColor:CGColorMakeRandomOpaque()];
   [self setNeedsDisplay]; 
}

@end 


int   main( int argc, char *argv[])
{
   UIWindow         *window;
   UIApplication    *app;
   NSTimer          *timer;
   id <UIOSWindow>  osWindow;
   NSUInteger       styleMask;
   
   app = [UIApplication sharedInstance];

   @autoreleasepool
   {
      styleMask = UIWindowStyleMaskDefault & ~UIWindowStyleRetained;
      window    = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 400.0, 400.0)
                            titleUTF8String:"Demo"
                                  styleMask:styleMask];

      [window setFrameRate:UIWindowFrameRateAsync];
      [window setBackgroundColor:CGColorMakeRGBA( 1.0, 0.75, 0.0, 1.0)];
      [app addWindow:window];

      timer = [[[NSTimer alloc] mulleInitWithRelativeTimeInterval:0.5
                                           repeatInterval:1.5
                                                   target:window 
                                                 selector:@selector( randomizeBackgroundColor:)
                                                 userInfo:nil 
                               fireUsesUserInfoAsArgument:YES] autorelease];
      [app addTimer:timer];

      timer = [[[NSTimer alloc] mulleInitWithRelativeTimeInterval:2.5
                                           repeatInterval:0.0
                                                   target:window 
                                                 selector:@selector( setWhiteBackgroundColor:)
                                                 userInfo:nil 
                               fireUsesUserInfoAsArgument:YES] autorelease];
      [app addTimer:timer];
   }
   return( [app run]);
}



