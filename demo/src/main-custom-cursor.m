#import "import.h"

#include <stdio.h>


static char   cursor_png[] =
#include "helpsel_eoa_2_72x72x32.png.inc"
;
#define s_cursor_png (sizeof( cursor_png) - 1)


int   main( int argc, char *argv[])
{
   UIWindow              *window;
   UIApplication         *app;
   UICursor              *cursor;
   NSUInteger            styleMask;
   struct CGBitmap       bitmap;

   app = [UIApplication sharedInstance];
   assert( app);

   @autoreleasepool
   {
      styleMask = UIWindowStyleMaskDefault & ~UIWindowStyleRetained;
      window    = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 400.0, 400.0)
                            titleUTF8String:"Demo"
                                  styleMask:styleMask];
      assert( window);
      [window setFrameRate:UIWindowFrameRateAsync];
      [window setBackgroundColor:CGColorMakeWithRGBA( 1.0, 0.75, 0.0, 1.0)];

      CGBitmapInitWithFileBytes( &bitmap, cursor_png, s_cursor_png);
      if( CGBitmapIsNull( bitmap))
      {
         mulle_fprintf( stderr, "failed to decode cur file\n");
         abort();
      }

      cursor = [app registerCursorBitmap:bitmap
                                 hotSpot:CGPixelPointZero
                        forKeyUTF8String:"ToolTip"
                     scaleToStandardSize:YES];
      if( ! cursor)
      {
         mulle_fprintf( stderr, "failed to register\n");
         abort();
      }

      CGBitmapDone( bitmap);

      [window setCursor:cursor];

      [app addWindow:window];
   }
   return( [app runApp]);
}



